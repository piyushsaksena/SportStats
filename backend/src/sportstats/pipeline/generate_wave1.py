def write_csv(path: Path, data: list):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(data[0].keys()))
        writer.writeheader()
        writer.writerows(data)
    logger.info("Wrote %s with %d rows", path.name, len(data))


def import_wave1_data(db):
    """Import Wave 1 curated datasets into the provided database session."""
    write_csv(DATA_DIR / "tournament_editions.csv", editions)
    write_csv(DATA_DIR / "matches.csv", matches)
    write_csv(DATA_DIR / "performance_stats.csv", stats)
    write_csv(DATA_DIR / "rankings.csv", rankings)
    write_csv(DATA_DIR / "olympic_results.csv", olympics)

    importer = CSVImporter(db)
    for dt in [
        "tournament_editions",
        "matches",
        "performance_stats",
        "rankings",
        "olympic_results",
    ]:
        csv_path = DATA_DIR / f"{dt}.csv"
        importer.import_csv(csv_path, dataset_type=dt, dry_run=False)


def main():
    write_csv(DATA_DIR / "tournament_editions.csv", editions)
    write_csv(DATA_DIR / "matches.csv", matches)
    write_csv(DATA_DIR / "performance_stats.csv", stats)
    write_csv(DATA_DIR / "rankings.csv", rankings)
    write_csv(DATA_DIR / "olympic_results.csv", olympics)

    # Ingest into database
    with get_db_context() as db:
        importer = CSVImporter(db)
        for dt in [
            "tournament_editions",
            "matches",
            "performance_stats",
            "rankings",
            "olympic_results",
        ]:
            csv_path = DATA_DIR / f"{dt}.csv"
            res = importer.import_csv(csv_path, dataset_type=dt, dry_run=False)
            logger.info(
                "Imported %s: status=%s, loaded=%d, rejected=%d",
                dt,
                res.status,
                res.rows_loaded,
                res.rows_rejected,
            )
            if res.issues:
                for is_ in res.issues:
                    logger.warning("  Issue: %s", is_)

    logger.info("Wave 1 Generation & Ingestion Completed Successfully!")


if __name__ == "__main__":
    main()
