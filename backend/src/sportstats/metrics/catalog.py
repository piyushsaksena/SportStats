def get_metrics_for_sport(sport_code: str) -> List[MetricDefinitionSpec]:
    """Retrieve list of metric definitions for a given sport."""
    return [m for m in METRICS_CATALOGUE if m.sport_code == sport_code]


def get_metric_by_code(sport_code: str, metric_code: str) -> Optional[MetricDefinitionSpec]:
    """Retrieve specific metric definition by sport and code."""
    for m in METRICS_CATALOGUE:
        if m.sport_code == sport_code and m.code == metric_code:
            return m
    return None


def get_catalogue_counts_by_sport() -> Dict[str, int]:
    """Compute number of metrics tracked per sport (maps to report Figure 3)."""
    counts: Dict[str, int] = {}
    for sport in SPORTS_REGISTRY:
        counts[sport["code"]] = len(get_metrics_for_sport(sport["code"]))
    return counts
